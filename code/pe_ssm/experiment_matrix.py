def select_experiments(
    topology: str | None = None,
    alloy: str | None = None,
    loading: str | None = None,
    maximum_nodes: int | None = None,
) -> tuple[ExperimentSpec, ...]:
    selected = []
    for experiment in EXPERIMENTS:
        if topology is not None and experiment.topology != topology:
            continue
        if alloy is not None and experiment.alloy != alloy:
            continue
        if loading is not None and experiment.loading != loading:
            continue
        if maximum_nodes is not None and experiment.mesh_nodes > maximum_nodes:
            continue
        selected.append(experiment)
    return tuple(selected)


def experiment_by_identity(identity: str) -> ExperimentSpec:
    for experiment in EXPERIMENTS:
        if experiment.identity == identity:
            return experiment
    raise KeyError(identity)
